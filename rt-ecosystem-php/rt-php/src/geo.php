function geo_norm(string $s): string
{
    $s = mb_strtolower(trim($s));
    $s = (string)preg_replace('/^(город|г\.)\s*/u', '', $s);
    $s = (string)preg_replace('/\s*(район|р-н)$/u', '', $s);
    return trim($s);
}

/** Возвращает [название места, широта, долгота]. Неизвестное место ставим в центр области. */
function geo_locate(string $inn, string $city, string $district, string $np): array
{
    $t = geo_table();
    $h = crc32($inn);
    $fx = (($h & 0xFFFF) / 65535 - 0.5) * 2;
    $fy = ((($h >> 16) & 0xFFFF) / 65535 - 0.5) * 2;
    $ck = geo_norm($city);
    $dk = geo_norm($district);
    if ($ck !== '') {
        if (isset($t['city'][$ck])) {
            [$n, $la, $lo, $j] = $t['city'][$ck];
            return [$n, $la + $fy * $j, $lo + $fx * $j * 1.4];
        }
        $name = mb_strtoupper(mb_substr($ck, 0, 1)) . mb_substr($ck, 1);
        return [$name, 47.6 + $fy * 0.9, 40.3 + $fx * 1.6];
    }
    if ($dk !== '' && isset($t['district'][$dk])) {
        [$la, $lo] = $t['district'][$dk];
        return [mb_strtoupper(mb_substr($dk, 0, 1)) . mb_substr($dk, 1) . ' р-н', $la + $fy * 0.18, $lo + $fx * 0.25];
    }
    $name = $dk !== '' ? $dk . ' р-н' : trim($np);
    return [$name, 47.6 + $fy * 0.9, 40.3 + $fx * 1.6];
}
